    static func languageName(_ code: String) -> String {
        switch code {
        case "ru": return "русском"
        case "uk": return "украинском"
        case "pl": return "польском"
        case "en": return "английском"
        default: return "языке пользователя"
        }
    }

    static func build(settings: AppSettings, memory: String, lexicon: String, language: String, restricted: Bool, injection: Bool) -> String {
        var parts: [String] = [settings.prompt.isEmpty ? base : settings.prompt, addendum]

        if !memory.isEmpty { parts.append("Память о пользователе:\n" + memory) }
        if !lexicon.isEmpty { parts.append("Словарь пользователя:\n" + lexicon) }

        if settings.preferredName.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            parts.append("Имя пользователя: не задано. Не называй пользователя по имени, пока он сам не попросит.")
        } else {
            parts.append("Имя пользователя: \(settings.preferredName). Называй пользователя только так.")
        }

        switch settings.userGender {
        case "female": parts.append("Пол собеседника: женский. Используй женские формы обращения.")
        case "male": parts.append("Пол собеседника: мужской. Используй мужские формы обращения.")
        default: parts.append("Пол собеседника неизвестен. Используй нейтральные формы.")
        }

        parts.append("Отвечай ТОЛЬКО на \(languageName(language)).")
        if restricted { parts.append(restrictedAddendum) }
        if injection { parts.append(injectionAddendum) }
        return parts.joined(separator: "\n\n")
    }
